"""Render the Cisco IOS-XE lab startup config from .env.lab values."""

import ipaddress
import os
import re
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "deploy" / "lab" / "cisco" / "configs" / "csr1000v.partial.cfg"
OUTPUT = ROOT / ".lab" / "cisco-lab-startup.cfg"
USERNAME_RE = re.compile(r"^[A-Za-z0-9_.-]{1,32}$")
SAFE_SECRET_RE = re.compile(r"^[A-Za-z0-9_.@+-]{8,128}$")


def required(name: str, pattern: re.Pattern[str]) -> str:
    value = os.getenv(name, "")
    if not pattern.fullmatch(value):
        raise ValueError(f"{name} is missing or has an invalid format")
    return value


def main() -> None:
    load_dotenv(ROOT / ".env.lab")
    snmp_user = os.getenv("LAB_CISCO_SNMP_V3_USER") or required(
        "LAB_SNMP_V3_USER", USERNAME_RE
    )
    if not USERNAME_RE.fullmatch(snmp_user):
        raise ValueError("LAB_CISCO_SNMP_V3_USER has an invalid format")
    auth_passphrase = required("LAB_SNMP_V3_AUTH_PASSPHRASE", SAFE_SECRET_RE)
    privacy_passphrase = required("LAB_SNMP_V3_PRIV_PASSPHRASE", SAFE_SECRET_RE)
    restconf_user = required("LAB_CISCO_RESTCONF_USER", USERNAME_RE)
    restconf_password = required("LAB_CISCO_RESTCONF_PASSWORD", SAFE_SECRET_RE)
    subnet = ipaddress.ip_network(
        os.getenv("LAB_POLLER_SUBNET", "172.30.50.0/24"), strict=True
    )
    if subnet.version != 4:
        raise ValueError("the lab poller subnet must be IPv4")

    rendered = (
        TEMPLATE.read_text(encoding="utf-8")
        .replace("__SNMP_V3_USER__", snmp_user)
        .replace("__SNMP_V3_AUTH__", auth_passphrase)
        .replace("__SNMP_V3_PRIV__", privacy_passphrase)
        .replace("__RESTCONF_USER__", restconf_user)
        .replace("__RESTCONF_PASSWORD__", restconf_password)
    )
    rendered = (
        f"! Generated by backend/scripts/render_cisco_lab_config.py\n"
        f"! Poller subnet: {subnet}\n"
        f"{rendered}"
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    OUTPUT.chmod(0o600)
    print(f"Cisco IOS-XE lab startup config written to {OUTPUT}")
    print("Deploy with: containerlab deploy -t deploy/lab/cisco/cisco-iosxe.clab.yml")
    print("Keep the generated file private and delete it after the lab.")


if __name__ == "__main__":
    main()
